// Ability values at T3 and their cast gates, for the roster profile (Milestone O
// §3.2.1, §3.5). Pure. Reads the raw API ability alongside the mapped HeroAbility,
// because the gate fields (cards, charge restore) are not on HeroAbility, and the
// engine's HeroAbility is left exactly as it is.

import type { HeroAbilityRaw } from "@/lib/api/deadlockApi";
import {
  DAMAGE_SECONDS_KEYS,
  isDamageRate,
  isSpiritScaled,
  mapHeroAbilities,
  type HeroAbility,
} from "@/lib/abilityCoefficients";
import type { SignatureSlot } from "@/lib/deadlock";
import { castsFromCooldown } from "./fight";

/**
 * What limits an ability's casts in a fight (§3.2.1):
 * - cooldown: the listed cooldown (nearly every ability);
 * - charges: a bank of charges with no shared cooldown, one restored every
 *   `restore` seconds (Graves Jar of Dead);
 * - channel: a damage rate whose duration outlasts its cooldown, so the cycle is
 *   duration + cooldown (Victor Aura of Suffering);
 * - resource: cards generated by bullet hits, thrown on a short cooldown (Wraith
 *   Card Trick);
 * - battery: charged by damage the caster TAKES, a share of max health per
 *   charge (Victor Pain Battery: "It takes damage equal to 40% of Victor's Max HP
 *   to gain a charge", CDR lowers the share; deadlock.wiki/Victor, 2026-11-07).
 *   Damage taken per fight is not modelled, so it counts the one charge assumed
 *   full at the start of a fight, in any fight length. Pending the user's call.
 */
export type CastGate =
  | { kind: "cooldown"; cooldown: number | null }
  | { kind: "battery"; healthShare: number; cooldown: number | null }
  | { kind: "charges"; charges: number; restore: number }
  | { kind: "channel"; cooldown: number; duration: number }
  | {
      kind: "resource";
      /** Cards banked at the start of a fight (AbilityCharges at T3). */
      banked: number;
      /** Seconds between throws; cooldown reduction doesn't change it (wiki). */
      throwCooldown: number;
      /** Card resource per body-shot hit, before the generation scale. */
      perBulletHit: number;
      /** Card resource per card. */
      perCard: number;
      /** CardResourceGenPctScale as a share (0.85). Also the CDR factor on generation. */
      genScale: number;
    };

/** Which pool an ability ranks in (§3.5). Spirit and weapon coefficients are different units. */
export type AbilityPool = "spirit" | "weapon" | "unscaled" | "utility";

export type AbilityT3 = {
  heroId: number;
  classname: string;
  name: string;
  slot: SignatureSlot;
  isUltimate: boolean;
  /** The damage property read; null = utility. */
  damageKey: string | null;
  /** Base damage at T3: per hit, or per second for a rate. 0 when none. */
  baseDamage: number;
  /** Damage per spirit power at T3. 0 = not spirit-scaled. */
  spiritScaling: number;
  /** Damage per weapon damage at T3. 0 = not weapon-scaled. */
  weaponScaling: number;
  /** Seconds one cast deals a rate for, at T3: damagePerCastFactor. 1 for a per-hit key. */
  perCastFactor: number;
  /** Cooldown at T3 (seconds); null = none listed. */
  cooldown: number | null;
  gate: CastGate;
  pool: AbilityPool;
};

/** What a fight's casts depend on besides the ability: only Card Trick reads it. */
export type CastContext = {
  /** Share of shots that land at the selected rank; null = unknown. */
  accuracy: number | null;
  /** The hero's base fire rate (boons don't change it; ranks are item-free). */
  bulletsPerSecond: number;
  /** Total cooldown reduction, 0-1 (§3.3). 0 for ranks. */
  cdr?: number;
  /** Fire-rate multiplier, for the resource gate's sensitivity (§3.3). Default 1. */
  fireRateScale?: number;
};

function num(v: number | string | undefined | null): number | null {
  if (v == null) return null;
  const n = typeof v === "number" ? v : parseFloat(String(v));
  return Number.isFinite(n) ? n : null;
}

/** Sum of an upgrade property's non-scale deltas over all three tiers. */
function flatDelta(ability: HeroAbility, stat: string): number {
  let sum = 0;
  for (const tier of ability.upgrades) {
    for (const c of tier.statChanges) {
      if (c.stat !== stat || c.scale) continue;
      sum += num(c.delta) ?? 0;
    }
  }
  return sum;
}

/** Sum of an upgrade property's scale deltas for one scale stat. */
function scaleDelta(ability: HeroAbility, stat: string, scaleStat: "spirit" | "weapon"): number {
  let sum = 0;
  for (const tier of ability.upgrades) {
    for (const c of tier.statChanges) {
      if (c.stat !== stat || !c.scale) continue;
      // Same reading as calculateAbilityDamage: no filter = spirit power.
      const isSpirit = !c.scaleStat || c.scaleStat === "ETechPower";
      const isWeapon = c.scaleStat === "EBaseWeaponDamageIncrease";
      if ((scaleStat === "spirit" && isSpirit) || (scaleStat === "weapon" && isWeapon)) {
        sum += num(c.delta) ?? 0;
      }
    }
  }
  return sum;
}

/**
 * A ramping damage rate is ranked at its maximum (§3.2.1: the wiki's "Max DPS"
 * for Aura of Suffering). The engine's damage key reads its minimum (MinDPS);
 * where a matching Max property exists, the profile reads that instead.
 */
function profileDamageKey(ability: HeroAbility, raw: HeroAbilityRaw): string | null {
  const key = ability.damageKey ?? null;
  if (key && key.startsWith("Min")) {
    const maxKey = `Max${key.slice(3)}`;
    const prop = raw.properties?.[maxKey];
    if (prop && (num(prop.value) ?? 0) > 0) return maxKey;
  }
  return key;
}

function gateOf(
  raw: HeroAbilityRaw,
  ability: HeroAbility,
  damageKey: string | null,
  cooldown: number | null,
  damageSeconds: number | null,
): CastGate {
  const p = raw.properties ?? {};
  const perCard = num(p.ResourcePerCard?.value) ?? 0;
  const perHit = num(p.CardResourcePerBulletHit?.value) ?? 0;
  const charges = (num(p.AbilityCharges?.value) ?? 0) + flatDelta(ability, "AbilityCharges");
  if (perCard > 0 && perHit > 0) {
    return {
      kind: "resource",
      banked: Math.max(0, charges),
      throwCooldown: cooldown ?? 0,
      perBulletHit: perHit,
      perCard,
      genScale: (num(p.CardResourceGenPctScale?.value) ?? 100) / 100,
    };
  }
  // Charged by damage taken: the cooldown is not what limits it.
  const batteryShare = num(p.StoredDamageHealthPercentRequired?.value) ?? 0;
  if (batteryShare > 0) {
    return { kind: "battery", healthShare: batteryShare / 100, cooldown };
  }
  // A bank of charges with no shared cooldown: the restore time is the gate.
  // Charges on an ability that ALSO has a cooldown count as the engine counts
  // them (no extra casts), a known gap (§8).
  const restore = num(p.AbilityCooldownBetweenCharge?.value) ?? 0;
  if (charges >= 2 && restore > 0 && !(cooldown != null && cooldown > 0)) {
    return { kind: "charges", charges, restore };
  }
  // A rate that lasts longer than its cooldown: the cycle is duration + cooldown,
  // with the cooldown starting when the channel ends.
  if (
    damageKey != null &&
    isDamageRate({ damageKey }) &&
    damageSeconds != null &&
    damageSeconds > 0 &&
    cooldown != null &&
    cooldown < damageSeconds
  ) {
    return { kind: "channel", cooldown, duration: damageSeconds };
  }
  return { kind: "cooldown", cooldown };
}

/** One ability at T3 (§3.5): base values plus every upgrade tier. */
export function abilityAtT3(heroId: number, ability: HeroAbility, raw: HeroAbilityRaw): AbilityT3 {
  const props = raw.properties ?? {};
  const damageKey = profileDamageKey(ability, raw);
  const overridden = damageKey != null && damageKey !== ability.damageKey;

  // Base and coefficients: the mapped ability's, unless the key was overridden.
  let base0 = ability.baseDamage ?? 0;
  let spirit0 = ability.spiritScaling ?? 0;
  let weapon0 = ability.weaponScaling ?? 0;
  if (overridden && damageKey) {
    const prop = props[damageKey];
    base0 = num(prop?.value) ?? 0;
    const scale = prop?.scale_function?.stat_scale ?? 0;
    const spiritScaled = prop ? isSpiritScaled(prop) : false;
    spirit0 = spiritScaled ? scale : 0;
    weapon0 =
      !spiritScaled && prop?.scale_function?.specific_stat_scale_type !== undefined ? scale : 0;
  }
  const baseDamage = damageKey ? base0 + flatDelta(ability, damageKey) : 0;
  const spiritScaling = damageKey ? spirit0 + scaleDelta(ability, damageKey, "spirit") : 0;
  const weaponScaling = damageKey ? weapon0 + scaleDelta(ability, damageKey, "weapon") : 0;

  const cd0 = num(props.AbilityCooldown?.value);
  const cdT3 = cd0 != null && cd0 > 0 ? cd0 + flatDelta(ability, "AbilityCooldown") : null;
  const cooldown = cdT3 != null && cdT3 > 0 ? cdT3 : null;

  // A rate's seconds per cast, with T3 duration upgrades on the key it came from.
  let damageSeconds: number | null = null;
  if (damageKey != null && isDamageRate({ damageKey })) {
    const secondsKey = DAMAGE_SECONDS_KEYS.find((k) => (num(props[k]?.value) ?? 0) > 0);
    if (secondsKey) {
      const s = (num(props[secondsKey]?.value) ?? 0) + flatDelta(ability, secondsKey);
      damageSeconds = s > 0 ? s : null;
    }
  }

  const deals = damageKey != null && (baseDamage > 0 || spiritScaling > 0 || weaponScaling > 0);
  const pool: AbilityPool = !deals
    ? "utility"
    : spiritScaling > 0
      ? "spirit"
      : weaponScaling > 0
        ? "weapon"
        : "unscaled";

  return {
    heroId,
    classname: ability.classname,
    name: ability.name,
    slot: ability.slot,
    isUltimate: ability.isUltimate,
    damageKey: deals ? damageKey : null,
    baseDamage: deals ? baseDamage : 0,
    spiritScaling: deals ? spiritScaling : 0,
    weaponScaling: deals ? weaponScaling : 0,
    perCastFactor: damageSeconds ?? 1,
    cooldown,
    gate: gateOf(raw, ability, damageKey, cooldown, damageSeconds),
    pool,
  };
}

/** A hero's four slotted abilities at T3, in slot order. Empty when the kit is missing. */
export function kitAtT3(
  heroId: number,
  abilitiesRaw: ReadonlyArray<HeroAbilityRaw>,
  heroItems: Record<string, string> | undefined,
): AbilityT3[] {
  const byClass = new Map(abilitiesRaw.map((a) => [a.class_name, a]));
  return mapHeroAbilities([...abilitiesRaw], heroItems).flatMap((ability) => {
    const raw = byClass.get(ability.classname);
    return raw ? [abilityAtT3(heroId, ability, raw)] : [];
  });
}

/**
 * Average casts per fight of `fightSeconds` (§3.2.1), fractional. For a channel
 * it is cast-equivalents: seconds of damage / duration, so per-cast damage x this
 * is the fight's damage for every gate alike. Null only for a resource gate with
 * no accuracy (cards from hits are unknown, never 0).
 */
export function castsInFight(
  ability: Pick<AbilityT3, "gate">,
  fightSeconds: number,
  ctx: CastContext,
): number | null {
  const r = Math.min(Math.max(ctx.cdr ?? 0, 0), 0.99);
  const gate = ability.gate;
  switch (gate.kind) {
    case "cooldown":
      return castsFromCooldown(gate.cooldown != null ? gate.cooldown * (1 - r) : 0, fightSeconds);
    case "battery":
      // The one charge banked at the start; recharging from damage taken is not
      // modelled (see CastGate), so CDR adds nothing here either.
      return 1;
    case "charges":
      return gate.charges - 1 + castsFromCooldown(gate.restore * (1 - r), fightSeconds);
    case "channel":
      return channelSeconds(gate, fightSeconds, r) / gate.duration;
    case "resource": {
      if (ctx.accuracy == null || !(ctx.accuracy > 0)) return null;
      const generated =
        (fightSeconds *
          ctx.bulletsPerSecond *
          (ctx.fireRateScale ?? 1) *
          ctx.accuracy *
          gate.perBulletHit *
          gate.genScale *
          (1 + gate.genScale * r)) /
        gate.perCard;
      const cap = gate.throwCooldown > 0 ? fightSeconds / gate.throwCooldown : Infinity;
      return Math.min(gate.banked + generated, cap);
    }
  }
}

/** A channel's seconds of damage in a fight: min(F, cycles x duration). */
export function channelSeconds(
  gate: Extract<CastGate, { kind: "channel" }>,
  fightSeconds: number,
  cdr = 0,
): number {
  const cycles = castsFromCooldown(gate.duration + gate.cooldown * (1 - cdr), fightSeconds);
  return Math.min(fightSeconds, cycles * gate.duration);
}

/** The coefficient an ability ranks on in its pool; null for unscaled and utility. */
export function scalingCoefficient(
  ability: Pick<AbilityT3, "pool" | "spiritScaling" | "weaponScaling">,
): number | null {
  if (ability.pool === "spirit") return ability.spiritScaling;
  if (ability.pool === "weapon") return ability.weaponScaling;
  return null;
}

/**
 * Kit scaling (§3.1): damage per fight gained per point of spirit power (or per
 * weapon damage), every ability at T3, summed over the kit's abilities in that
 * pool. 0 is a real value (no ability in the pool). Null when the kit is missing
 * or a pool ability's casts are unknown.
 */
export function kitScaling(
  kit: ReadonlyArray<AbilityT3> | null | undefined,
  pool: "spirit" | "weapon",
  fightSeconds: number,
  ctx: CastContext,
): number | null {
  if (!kit || kit.length === 0) return null;
  // No ability with a readable damage value (Solomon, 2026-11-07: his damage
  // properties carry no css_class, so the shared mapper reads none) is unknown,
  // not a real 0. Ranking him last would state a fact the data doesn't have.
  if (kit.every((a) => a.pool === "utility")) return null;
  let sum = 0;
  for (const ability of kit) {
    if (ability.pool !== pool) continue;
    const casts = castsInFight(ability, fightSeconds, ctx);
    const coef = scalingCoefficient(ability);
    if (casts == null || coef == null) return null;
    sum += coef * ability.perCastFactor * casts;
  }
  return sum;
}
